/**
 * Restituisce l'oggetto appartamento con i campi testuali sovrascritti nella lingua corrente.
 */
export const getLocalizedApartment = (apt, lang = "it") => {
  if (!apt) return apt;
  const translation = APARTMENT_TRANSLATIONS[apt.id]?.[lang] || APARTMENT_TRANSLATIONS[apt.id]?.it;
  if (!translation) return apt;

  return {
    ...apt,
    description: translation.description || apt.description,
    pets_note: translation.pets_note || apt.pets_note,
    specs: {
      ...apt.specs,
      ...(translation.specs || {})
    }
  };
};
